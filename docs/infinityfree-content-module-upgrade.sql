-- Add the database tables used by the Admin Blog and Portfolio modules.
-- Safe for an existing InfinityFree database; it does not alter existing rows.

CREATE TABLE IF NOT EXISTS blog_posts (
  id INT AUTO_INCREMENT NOT NULL,
  slug VARCHAR(120) NOT NULL,
  title VARCHAR(120) NOT NULL,
  excerpt LONGTEXT NOT NULL,
  cover_image VARCHAR(255) DEFAULT '' NOT NULL,
  cover_image_alt VARCHAR(255) DEFAULT '' NOT NULL,
  body LONGTEXT NOT NULL,
  icon VARCHAR(40) DEFAULT 'pen-line' NOT NULL,
  category VARCHAR(40) NOT NULL,
  sort_order INT DEFAULT 0 NOT NULL,
  is_published TINYINT DEFAULT 0 NOT NULL,
  status VARCHAR(20) DEFAULT 'draft' NOT NULL,
  author_name VARCHAR(120) DEFAULT '' NOT NULL,
  author_role VARCHAR(120) DEFAULT '' NOT NULL,
  author_avatar VARCHAR(255) DEFAULT '' NOT NULL,
  meta_title VARCHAR(160) DEFAULT '' NOT NULL,
  meta_description VARCHAR(320) DEFAULT '' NOT NULL,
  meta_keywords VARCHAR(255) DEFAULT '' NOT NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE INDEX uniq_blog_posts_slug (slug),
  INDEX idx_blog_posts_slug (slug),
  INDEX idx_blog_posts_status (status),
  INDEX idx_blog_posts_published (is_published),
  INDEX idx_blog_posts_category (category),
  PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS case_studies (
  id INT AUTO_INCREMENT NOT NULL,
  slug VARCHAR(120) NOT NULL,
  title VARCHAR(120) NOT NULL,
  excerpt LONGTEXT NOT NULL,
  cover_image VARCHAR(255) DEFAULT '' NOT NULL,
  cover_image_alt VARCHAR(255) DEFAULT '' NOT NULL,
  body LONGTEXT NOT NULL,
  icon VARCHAR(40) DEFAULT 'code2' NOT NULL,
  project_type VARCHAR(80) NOT NULL,
  sort_order INT DEFAULT 0 NOT NULL,
  is_published TINYINT DEFAULT 0 NOT NULL,
  status VARCHAR(20) DEFAULT 'draft' NOT NULL,
  testimonial_id INT DEFAULT NULL,
  client_company VARCHAR(120) DEFAULT '' NOT NULL,
  client_name VARCHAR(120) DEFAULT '' NOT NULL,
  client_role VARCHAR(120) DEFAULT '' NOT NULL,
  client_website VARCHAR(255) DEFAULT '' NOT NULL,
  challenge LONGTEXT NOT NULL,
  solution LONGTEXT NOT NULL,
  results LONGTEXT NOT NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE INDEX uniq_case_studies_slug (slug),
  INDEX idx_case_studies_slug (slug),
  INDEX idx_case_studies_status (status),
  INDEX idx_case_studies_published (is_published),
  INDEX idx_case_studies_project_type (project_type),
  PRIMARY KEY (id)
);
